// Regénère THIRD-PARTY-NOTICES.md : les licences de tout ce que uehub embarque.
// Les crates Rust viennent de cargo about (about.toml, about.hbs), les paquets de
// l'interface de desktop/node_modules. À relancer quand Cargo.lock ou package-lock.json
// change :
//
//   cargo install cargo-about --locked --features cli
//   (cd desktop && npm ci) && node scripts/third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const modules = join(root, "desktop/node_modules");

// Les paquets npm que l'interface embarque : ses dépendances, et les leurs. Les outils
// de développement (Vite, TypeScript, Vitest) ne finissent pas dans l'app.
function npmPackages() {
  const found = new Map();
  const visit = (name) => {
    if (found.has(name)) return;
    const dir = join(modules, name);
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    found.set(name, { pkg, dir });
    for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep);
  };
  const app = JSON.parse(
    readFileSync(join(root, "desktop/package.json"), "utf8"),
  );
  for (const dep of Object.keys(app.dependencies)) visit(dep);
  return [...found.values()].sort((a, b) =>
    a.pkg.name.localeCompare(b.pkg.name),
  );
}

// Le texte de licence que le paquet fournit (LICENSE, LICENSE.md, LICENSE-MIT…).
function licenseTexts(dir) {
  return readdirSync(dir)
    .filter((file) => /^(licen[cs]e|copying)/i.test(file))
    .sort()
    .map((file) => readFileSync(join(dir, file), "utf8").trim());
}

const rust = execFileSync(
  "cargo",
  ["about", "generate", "--workspace", "about.hbs"],
  { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);

let npm = "";
for (const { pkg, dir } of npmPackages()) {
  npm += `### ${pkg.name} ${pkg.version} (${pkg.license})\n\n`;
  const texts = licenseTexts(dir);
  if (texts.length === 0)
    throw new Error(`${pkg.name} : aucun fichier de licence`);
  for (const text of texts) npm += "```text\n" + text + "\n```\n\n";
}

const notices = `# Third-party notices

uehub is distributed under its own license (see [LICENSE](LICENSE)). It includes the
following open-source software, each under its own license, whose terms are
reproduced below. Nothing in uehub's license limits the rights these licenses give you.

The source code of each Rust crate is available on [crates.io](https://crates.io), and
that of each npm package on [npmjs.com](https://www.npmjs.com), at the versions listed.

This file is generated by \`node scripts/third-party-notices.mjs\`: do not edit it by hand.

## Interface (npm packages and font)

${npm}## Rust crates

${rust}`;

if (!existsSync(join(root, "LICENSE"))) throw new Error("LICENSE introuvable");
// Quelques licences arrivent avec des fins de ligne Windows : le fichier n'en garde
// aucune, pour qu'un éditeur ou Git ne le modifie pas dans le dos du script.
const text = notices.replace(/\r\n?/g, "\n").trimEnd() + "\n";
writeFileSync(join(root, "THIRD-PARTY-NOTICES.md"), text);
console.log("THIRD-PARTY-NOTICES.md écrit");
